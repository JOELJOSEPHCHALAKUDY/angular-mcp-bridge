import { test, expect } from '@playwright/test';
import { selectInspectorTab } from './inspector.js';
async function openLab(page: import('@playwright/test').Page) {
  await page.goto('/');
  await page.getByRole('button', { name: /Angular integration lab open_lab/ }).click();
  await page.getByRole('button', { name: 'Run tool', exact: false }).click();
  const view = page.frameLocator('iframe');
  await expect(view.getByRole('heading', { name: 'Explore the bridge.' })).toBeVisible();
  await expect(view.locator('.environment')).toContainText('lab_selection ready');
  return view;
}
test('second Angular view exposes UI tools, modal templates, resources and teardown', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const view = await openLab(page);
  await expect(view.getByRole('textbox', { name: 'Shared note' })).not.toHaveValue('');
  await selectInspectorTab(page, 'View tools');
  await page.getByRole('combobox', { name: 'View tool', exact: true }).selectOption('lab_selection');
  await page.getByRole('textbox', { name: 'View tool arguments' }).fill('{"selection":"Resources"}');
  await page.getByRole('button', { name: 'Call view tool' }).click();
  await expect(view.getByRole('button', { name: 'Resources', exact: true })).toHaveClass(/selected/);
  await view.getByRole('button', { name: 'Open Angular modal' }).click();
  await expect(view.getByRole('dialog')).toBeVisible();
  await expect(view.getByRole('dialog')).toContainText('Selected: Resources');
  await view.getByRole('button', { name: 'Close dialog' }).click();
  await expect(view.getByRole('dialog')).toHaveCount(0);
  await view.getByRole('textbox', { name: 'Shared note' }).fill('Verified Angular resource write');
  await view.getByRole('button', { name: 'Save note' }).click();
  await expect(view.getByRole('status').filter({ hasText: 'Note saved.' })).toBeVisible();
  await selectInspectorTab(page, 'Resources');
  await page.getByRole('combobox', { name: 'Resource', exact: true }).selectOption('bridge://lab/notes');
  await expect(page.locator('.inspector-content')).toContainText('Verified Angular resource write');
  await view.getByRole('button', { name: 'Share selection with model' }).click();
  await view.getByRole('checkbox').check();
  await selectInspectorTab(page, 'Model context');
  await expect(page.locator('.inspector-content')).toContainText('Resources');
  const downloading = page.waitForEvent('download');
  await view.getByRole('button', { name: 'Download', exact: true }).click();
  expect((await downloading).suggestedFilename()).toBe('angular-view-export.txt');
  await view.getByRole('button', { name: 'Close view', exact: true }).click();
  await expect(page.locator('.preview-status')).toHaveText('closed');
  await page.getByRole('button', { name: 'Reload preview', exact: true }).click();
  await expect(view.getByRole('heading', { name: 'Explore the bridge.' })).toBeVisible();
  await expect(view.locator('.environment')).toContainText('lab_selection ready');
  expect(errors).toEqual([]);
});
